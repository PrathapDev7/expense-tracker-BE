require('dotenv').config();

const fs = require('fs');
const path = require('path');
const {uploadImageBuffer} = require('../config/s3');

const contentTypesByExtension = {
    '.gif': 'image/gif',
    '.ico': 'image/x-icon',
    '.jpeg': 'image/jpeg',
    '.jpg': 'image/jpeg',
    '.png': 'image/png',
    '.svg': 'image/svg+xml',
    '.webp': 'image/webp',
};

const [sourceArg, outputArg, prefixArg] = process.argv.slice(2);

if (!sourceArg || !outputArg) {
    console.error('Usage: npm run upload:images -- /path/to/source /path/to/output.js [s3-prefix]');
    process.exit(1);
}

const sourceRoot = path.resolve(sourceArg);
const outputPath = path.resolve(outputArg);
const s3Prefix = (prefixArg || 'wealthify-rn-assets').replace(/^\/+|\/+$/g, '');

if (!fs.existsSync(sourceRoot) || !fs.statSync(sourceRoot).isDirectory()) {
    console.error(`Source directory not found: ${sourceRoot}`);
    process.exit(1);
}

const toPosixPath = (filePath) => filePath.split(path.sep).join('/');

const encodeKeySegment = (segment) => segment
    .replace(/[^a-zA-Z0-9._-]/g, '-')
    .replace(/-+/g, '-')
    .toLowerCase();

const createStableKey = (relativePath) => [
    s3Prefix,
    ...toPosixPath(relativePath).split('/').map(encodeKeySegment),
].join('/');

const findImages = (dir, files = []) => {
    for (const entry of fs.readdirSync(dir, {withFileTypes: true})) {
        const fullPath = path.join(dir, entry.name);

        if (entry.isDirectory()) {
            findImages(fullPath, files);
            continue;
        }

        if (!entry.isFile()) continue;

        const extension = path.extname(entry.name).toLowerCase();
        if (contentTypesByExtension[extension]) files.push(fullPath);
    }

    return files;
};

const writeManifest = (uploads) => {
    const manifest = uploads.reduce((acc, upload) => {
        acc[upload.assetPath] = {uri: upload.url};
        return acc;
    }, {});

    const content = [
        '// Generated by expense-tracker-BE/scripts/upload-image-directory.js',
        '// Do not edit by hand; rerun the upload script after asset changes.',
        `export const remoteImages = ${JSON.stringify(manifest, null, 4)};`,
        '',
        'export const remoteImage = (assetPath) => remoteImages[assetPath];',
        '',
    ].join('\n');

    fs.mkdirSync(path.dirname(outputPath), {recursive: true});
    fs.writeFileSync(outputPath, content);
};

const run = async () => {
    const imagePaths = findImages(sourceRoot).sort();
    const uploads = [];

    for (const imagePath of imagePaths) {
        const relativePath = toPosixPath(path.relative(sourceRoot, imagePath));
        const assetPath = `assets/${relativePath}`;
        const extension = path.extname(imagePath).toLowerCase();
        const key = createStableKey(relativePath);
        const uploadedImage = await uploadImageBuffer({
            buffer: fs.readFileSync(imagePath),
            key,
            contentType: contentTypesByExtension[extension],
        });

        uploads.push({
            assetPath,
            key: uploadedImage.key,
            url: uploadedImage.url,
        });
        console.log(`${assetPath} -> ${uploadedImage.url}`);
    }

    writeManifest(uploads);
    console.log(`Uploaded ${uploads.length} images.`);
    console.log(`Manifest written to ${outputPath}`);
};

run().catch((error) => {
    console.error(error.message || error);
    process.exit(1);
});
